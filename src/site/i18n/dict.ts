export function translate(locale: Locale, key: UiKey, vars?: Record<string, string | number>): string {
  const s = UI[locale][key] ?? UI.de[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m)) : s;
}
